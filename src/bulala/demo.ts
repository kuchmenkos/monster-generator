  "Красота — понятие растяжимое. Я тоже немножко растяжимый.",
  "Это не складочки. Это места для хранения нежности.",
  "Я съел твой страх. На вкус как вчерашнее печенье.",
  "Поверни меня. Там у меня аргументы получше.",
  "Не смотри так. Я тоже тебя впервые вижу.",
