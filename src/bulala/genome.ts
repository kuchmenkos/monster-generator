function surprise(g: Genome) {
  return traitKeys.reduce(
    (v, k) => v - Math.log2(catalogs[k][g.genes[k]].w / 100),
    0,
  );
}
// Reproducible reference population. Tail probability compares the same weighted
// sampler used for new creatures, never local collection size or cosmetic sliders.
const reference = Array.from({ length: 16000 }, (_, i) =>
  surprise(generate("reference-" + i)),
).sort((a, b) => a - b);
export function rarity(g: Genome) {
  const score = surprise(g);
  let lo = 0,
    hi = reference.length;
  while (lo < hi) {
    const mid = (lo + hi) >>> 1;
    if (reference[mid] < score - 1e-9) lo = mid + 1;
    else hi = mid;
  }
  const tail =
    Math.max(1 / reference.length, (reference.length - lo) / reference.length) *
    100;
  return {
    tail,
    score,
    tier:
      tail <= 1
        ? "Легендарный"
        : tail <= 8
          ? "Эпический"
          : tail <= 30
            ? "Редкий"
            : "Необычный",
    color:
      tail <= 1
        ? "#b5842a"
        : tail <= 8
          ? "#8f69b0"
          : tail <= 30
            ? "#568568"
            : "#728092",
    combination: traitKeys.reduce(
      (p, k) => (p * catalogs[k][g.genes[k]].w) / 100,
      1,
    ),
  };
}
