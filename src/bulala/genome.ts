export function rng(seed: string) {
  let h = 2166136261;
  for (const c of seed) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export function generate(seed: string = crypto.randomUUID()): Genome {
  const genes = {} as Genome["genes"];
  for (const k of traitKeys) {
    let n = rng(seed + "/gene/" + k)() * 100;
    genes[k] = catalogs[k].length - 1;
    for (let i = 0; i < catalogs[k].length; i++) {
      n -= catalogs[k][i].w;
      if (n < 0) {
        genes[k] = i;
        break;
      }
    }
  }
  return { version: 3, seed, genes, chaos: 55 };
}
export function validGenome(value: unknown): value is Genome {
  if (!value || typeof value !== "object") return false;
  const g = value as Genome;
  return (
    g.version === 3 &&
    typeof g.seed === "string" &&
    /^[a-zA-Z0-9-]{1,40}$/.test(g.seed) &&
    Number.isFinite(g.chaos) &&
    g.chaos >= 0 &&
    g.chaos <= 100 &&
    !!g.genes &&
    traitKeys.every(
      (k) =>
        Number.isInteger(g.genes[k]) &&
        g.genes[k] >= 0 &&
        g.genes[k] < catalogs[k].length,
    )
  );
}
export function encode(g: Genome) {
  return btoa(
    JSON.stringify({
      version: 3,
      seed: g.seed,
      genes: Object.fromEntries(traitKeys.map((k) => [k, g.genes[k]])),
      chaos: g.chaos,
    }),
  );
}
/** Shared migration for URL DNA and local collections. Never regenerate old categories. */
export function migrateGenome(value: unknown): Genome | null {
  if (!value || typeof value !== "object") return null;
  const v = value as {
    version: number;
    seed: string;
    genes: Record<string, number>;
    chaos: number;
  };
  if (v.version === 3) return validGenome(v) ? structuredClone(v) : null;
  if (v.version === 2) {
    const result = {
      ...v,
      version: 3,
      genes: { ...v.genes, pupil: rng(v.seed + "/pupil-v2")() > 0.5 ? 1 : 0 },
    };
    return validGenome(result) ? result : null;
  }
  if (v.version !== 1 || !v.genes || typeof v.genes !== "object") return null;
  const genes = { ...v.genes };
  for (const k of ["mouth", "chin", "horns"]) genes[k] ??= 0;
  const oldMouth = genes.mouth;
  const defaults = generate(v.seed || "migration").genes;
  genes.teeth = [3, 2, 4, 1, 5][oldMouth] ?? 0;
  genes.mouth = [2, 1, 2, 0, 2][oldMouth] ?? 0;
  genes.finish = genes.skin === 3 ? 2 : 0;
  genes.pattern = genes.skin === 2 ? 3 : 0;
  genes.brows = defaults.brows;
  genes.eyeCut = genes.eyes === 1 ? 2 : 0;
  genes.pupil = rng(v.seed + "/pupil-v2")() > 0.5 ? 1 : 0;
  const result = { version: 3, seed: v.seed, genes, chaos: v.chaos };
  return validGenome(result) ? result : null;
}
export function decode(s: string): Genome | null {
  try {
    return migrateGenome(JSON.parse(atob(s)));
  } catch {
    return null;
  }
}
/** Shared pupil type; heteromorphism is exclusively a 5% event for two eyes. */
export function pupilTypes(g: Genome, count: number) {
  const r = rng(g.seed + "/pupil-v2"),
    legacyBase = r() > 0.5 ? 1 : 0,
    base = g.genes.pupil ?? legacyBase;
  const different = count === 2 && r() < 0.05;
  const odd = r() < 0.5 ? 0 : 1;
  return Array.from({ length: count }, (_, i) =>
    different && i === odd
      ? base < 2
        ? 1 - base
        : (base + 1 + Math.floor(rng(g.seed + "/odd-pupil")() * 5)) % 6
      : base,
  );
}
